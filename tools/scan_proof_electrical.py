def match_key(value):
    """Normalise only for matching, retaining mathematical symbols in the source."""
    return re.sub(r'[\s，,。；;：:、“”"（）()]+', '', unicodedata.normalize('NFKC',value)).lower()


def correct(stem, blocks):
    if stem.startswith("electrical-notes-"):
        catalogue = ELECTRICAL
    elif stem.startswith("computing-systems-"):
        catalogue = COMPUTING
    else:
        return blocks
    page = int(stem.rsplit("-",1)[1])
    rules = catalogue.get(page,{})
    corrected=[]
    for kind,value in blocks:
        if kind not in ('p','h'):
            corrected.append([kind,value])
            if stem == 'electrical-notes-008' and kind == 'f' and value == '1':
                corrected.append(['math', r'\dot U_2=150\cos(-30^\circ)+j150\sin(-30^\circ)=(129.9-j75)\,\mathrm V'])
            continue
        lookup=match_key(value)
        replacement=next((v for k,v in rules.items() if match_key(k) in lookup),None)
        if replacement is not None:
            for line in replacement.splitlines():
                if line.startswith('= '):
                    corrected.append(['math',line[2:]])
                elif line.startswith('# '):
                    corrected.append(['h',line[2:]])
                elif line:
                    corrected.append(['p',line])
            continue
        text=value.strip()
        for old,new in TERMS.items():
            text=text.replace(old,new)
        text=re.sub(r'\s*([，。；：、！？])\s*',r'\1',text)
        text=re.sub(r'(?<=[\u3400-\u9fff])\s+(?=[\u3400-\u9fff])','',text)
        corrected.append([kind,text])
    return corrected
